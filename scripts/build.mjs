import { readFile, writeFile, watch } from "node:fs/promises";
import { posix } from "node:path";
const root = new URL("../", import.meta.url);
const files = ["src/headings.js", "src/styles.js", "src/rail.js", "src/plugin.js"];
async function build() {
  const modules = [];
  for (const file of files) {
    let source = await readFile(new URL(file, root), "utf8");
    source = source.replace(/require\(["'](\.[^"']+)["']\)/g, (_, target) => {
      let resolved = posix.normalize(posix.join(posix.dirname(file), target));
      if (!resolved.endsWith(".js")) resolved += ".js";
      if (!files.includes(resolved)) throw new Error(`Missing bundled module ${resolved}`);
      return `require(${JSON.stringify(resolved)})`;
    });
    modules.push(`${JSON.stringify(file)}: function(require, module, exports) {\n${source}\n}`);
  }
  const bundle = `/* siyuan-general-outline v1.0.0 — generated by scripts/build.mjs */\n"use strict";\nmodule.exports = (() => {\nconst modules = {${modules.join(",\n")}};\nconst cache = Object.create(null);\nfunction load(id) { if (!modules[id]) return require(id); if (cache[id]) return cache[id].exports; const item = cache[id] = {exports:{}}; modules[id](load,item,item.exports); return item.exports; }\nreturn load("src/plugin.js");\n})();\n`;
  await writeFile(new URL("index.js", root), bundle);
  console.log("Built index.js");
}
await build();
if (process.argv.includes("--watch")) {
  for await (const event of watch(new URL("src/", root))) if (event.filename?.endsWith(".js")) { try { await build(); } catch (error) { console.error(error.message); } }
}
